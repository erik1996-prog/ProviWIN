-- 04_DATABASE/09_MIGRATIONS/001_SGS_PERFIL.sql
-- Perfiles de acceso (roles personalizados) de SGS.
-- Tablas NUEVAS e independientes: no modifican ninguna tabla existente de win_telecom_db,
-- por lo que el sistema de origen no se ve afectado.
--
-- Un perfil = rol base (usuarios.rol) + conjunto de permisos. Al asignarlo a un usuario,
-- SGS escribe su rol base en usuarios.rol y sus permisos en usuario_permisos, de modo que
-- la autorización (Auth::can) funciona igual en SGS y en el sistema de origen.

CREATE TABLE IF NOT EXISTS SGS_PERFIL (
    PERFIL_ID          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOMBRE             VARCHAR(80)  NOT NULL,
    DESCRIPCION        VARCHAR(255) NULL,
    ROL_BASE           VARCHAR(30)  NOT NULL,
    PERMISOS           TEXT         NOT NULL COMMENT 'JSON: lista de claves de permiso habilitadas',
    ACTIVO             TINYINT(1)   NOT NULL DEFAULT 1,
    CREADO_POR         INT          NULL,
    FECHA_CREACION     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHA_ACTUALIZACION DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT PK_SGS_PERFIL PRIMARY KEY (PERFIL_ID),
    CONSTRAINT UQ_SGS_PERFIL_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT FK_SGS_PERFIL_CREADO_POR FOREIGN KEY (CREADO_POR) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SGS_USUARIO_PERFIL (
    USUARIO_ID     INT          NOT NULL,
    PERFIL_ID      INT UNSIGNED NOT NULL,
    ASIGNADO_POR   INT          NULL,
    FECHA_ASIGNACION DATETIME   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SGS_USUARIO_PERFIL PRIMARY KEY (USUARIO_ID),
    CONSTRAINT FK_SGS_USUARIO_PERFIL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT FK_SGS_USUARIO_PERFIL_PERFIL FOREIGN KEY (PERFIL_ID) REFERENCES SGS_PERFIL(PERFIL_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SGS_USUARIO_PERFIL_ASIGNADO FOREIGN KEY (ASIGNADO_POR) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX IX_SGS_USUARIO_PERFIL_PERFIL_001 ON SGS_USUARIO_PERFIL (PERFIL_ID);
